/// An absent key marks a fixed numeric ceiling; an absent bound marks a semantic refusal.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct LimitBound {
    pub value: u64,
    pub key: Option<LimitKey>,
    pub unit: LimitUnit,
}
impl LimitBound {
    #[must_use]
    pub const fn configured(value: u64, key: LimitKey, unit: LimitUnit) -> Self {
        Self { value, key: Some(key), unit }
    }
    #[must_use]
    pub const fn fixed(value: u64, unit: LimitUnit) -> Self {
        Self { value, key: None, unit }
    }
}
